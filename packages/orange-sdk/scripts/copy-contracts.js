#!/usr/bin/env node
/**
 * Script to copy generated smart contract clients from smart-contracts package
 * Run with: npm run copy-contracts
 */

import { promises as fs } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const SOURCE_DIR = path.resolve(__dirname, '../../../smart-contracts/src/clients');
const TARGET_DIR = path.resolve(__dirname, '../src/contracts/generated');

const CONTRACT_CLIENTS = [
  'OrangeSubscriptionsClient.ts',
  'OrangeNodeRegistryClient.ts',
  'OrangeGatewayRegistryClient.ts',
];

async function copyContracts() {
  console.log('📦 Copying generated contract clients...\n');

  // Ensure target directory exists
  await fs.mkdir(TARGET_DIR, { recursive: true });

  for (const clientFile of CONTRACT_CLIENTS) {
    const sourcePath = path.join(SOURCE_DIR, clientFile);
    const targetPath = path.join(TARGET_DIR, clientFile);

    try {
      // Check if source file exists
      await fs.access(sourcePath);

      // Copy the file
      await fs.copyFile(sourcePath, targetPath);
      console.log(`  ✅ ${clientFile}`);
    } catch (error) {
      if (error.code === 'ENOENT') {
        console.error(`  ❌ ${clientFile} - Source file not found`);
        console.error(`     Expected at: ${sourcePath}`);
      } else {
        console.error(`  ❌ ${clientFile} - ${error.message}`);
      }
    }
  }

  // Create index.ts that re-exports main client classes (avoid naming conflicts)
  const indexContent = `/**
 * Generated Smart Contract Clients
 * 
 * These files are auto-generated by @algorandfoundation/algokit-client-generator.
 * Do not modify them directly. Run \`npm run copy-contracts\` to update.
 */

// Export only the main client classes to avoid naming conflicts
export {
  OrangeSubscriptionsContractClient,
  OrangeSubscriptionsContractFactory,
} from './OrangeSubscriptionsClient';

export {
  OrangeNodeRegistryClient,
  OrangeNodeRegistryFactory,
} from './OrangeNodeRegistryClient';

export {
  OrangeGatewayRegistryClient,
  OrangeGatewayRegistryFactory,
} from './OrangeGatewayRegistryClient';
`;

  await fs.writeFile(path.join(TARGET_DIR, 'index.ts'), indexContent);
  console.log(`  ✅ index.ts (generated)\n`);

  console.log('✨ Contract clients copied successfully!\n');
}

copyContracts().catch((error) => {
  console.error('Failed to copy contracts:', error);
  process.exit(1);
});
